         f"**Extraction model (literal id): `{cfg['model']['id']}`** — max_tokens full text {cfg['model']['max_tokens_fulltext']}, abstract {cfg['model']['max_tokens_abstract']}, screen {cfg['model']['max_tokens_screen']}.", "",
         "## Pinned parameters", "", _tbl([(k, v) for k, v in pin.items()], ["parameter", "value"]), "",
         "Deviations from the calibrated block (validator warnings at load): " + ("; ".join(cfg.get("_warnings") or []) or "none") + ".", "",
         "## Stages run", "",
         f"1. **Draw** (pipeline/draw.py): Europe PMC, one query per theme {list((cfg.get('draw') or {}).get('themes', {}).keys())}, years {cfg['year_range']['start']}–{cfg['year_range']['end']}, SRC:MED, HAS_ABSTRACT:y. "
         + (f"Universe {draw_report.get('unique_pmids')} unique PMIDs; contamination-regex flagged {draw_report.get('flagged_contamination')} (flag, not exclusion). " if draw_report else "")
