    area = cfg["area"]["name"]; slug = cfg["_pkg_slug"]
    inv_rows = [(c["name"], "ok" if c["ok"] else "**FAIL**", json.dumps({k: v for k, v in c.items() if k not in ("name", "ok")}, default=str)[:160])
                for c in inv["checks"]]
    n_ok = sum(1 for c in inv["checks"] if c["ok"])
    cov = st["coverage"]["papers_yielding_of_rostered"]
    strata = st["fulltext_strata"]
    cen_rows = []
    for s in (census or {}).get("strata", []):
        nc = s["negative_control"]
        cen_rows.append((s["stratum"], s["n_checked"], s["n_traceable"], f"{s['traceable_pct']}%" if s["traceable_pct"] is not None else "—",
                         s["n_no_source_text"], f"{nc['n_false_positives']}/{nc['n_control']} ({nc['false_positive_pct']}%)" if nc["n_control"] else "—", nc["verdict"]))
    L = []
    A = L.append
    A(f"# {slug}-{version} — {area}")
    A("")
    if dry_run_note:
        A(f"> **{dry_run_note}**")
        A("")
    A(f"**{fmt(st['findings'])} machine-extracted findings from {fmt(st['papers'])} papers** ({cfg['tier']['label']}; "
      f"chunks {st['chunk_ids']}; years {st['year_range'][0]}–{st['year_range'][1]}; source stream Europe PMC; "
      f"extraction model `{cfg['model']['id']}`).")
    A("")
    A("## Read this before the data")
    A("")
    A("**Scientific fidelity is unmeasured.** Every check in `qa/` verifies well-formedness — that a quote is verbatim in "
      "its source, that an identifier denotes the named entity, that counts conserve. Nothing here tests whether a finding "
      "correctly interprets its paper. Every row is a pointer to a paper worth reading, not a fact to cite.")
