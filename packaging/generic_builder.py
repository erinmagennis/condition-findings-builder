         f"2. **Screen** (pipeline/screen.py): rule arm = config.screen.rule_anchors; LLM arm = rendered scope (`code/scope_rendered.txt`) + title/abstract, verbatim span required, `{cfg['model']['id']}`, max_tokens {cfg['model']['max_tokens_screen']}; reconciled with helpers.screen_reconcile.",
         f"3. **Extract** (pipeline/pipeline.py via pipeline/driver.py): names only, ids forbidden in the prompt and stripped by the parser guard; `unescape_source_text={cfg['unescape_source_text']}` (entities decoded twice, inline tags stripped) BEFORE the model read the text; `retain_source_text=true` — the exact text handed to the model is archived per chunk.",
