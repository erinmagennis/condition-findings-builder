"""Generic single-package builder — corpus + config/<area>.yaml -> ONE self-contained package.

Added 2026-09-30 (EDS dry run). `build_packages.py` is the POTS build's five-package
reproduction script: it hard-wires `tier1/tier2a/tier2b/tier3/tier4`, the `site` block, the
Tier-2 wave split and ~40 cross-tier harmonization columns that the Tier-4-generation pipeline
does not emit. `PACKAGING.md` described it as "corpus + config -> N packages"; it was not, so a
second area had no packaging path at all. This module IS that path for the common case — a new
area's first package — and reuses the legacy script's byte-level primitives (`sha256f`,
`make_tarball`, `fill_template`) so manifests, checksums and tarballs are produced the same way.

    python build_packages.py --area-config config/<area>.yaml --corpus findings.parquet \
        --roster roster.parquet --qa-dir qa/ --scope-dir scope/ --out build --version v0-dryrun \
        [--slug NAME] [--dry-run-note "..."]

Folder shape (PACKAGING.md): data/ docs/ qa/ scope/ code/ deposit/ + README.md MANIFEST.json
CHECKSUMS.sha256 LICENSE CITATION.cff .zenodo.json. `MANIFEST.json` carries `condition_enum`
(from the config) and `model_id`; `code/verify_package.py` is `pipeline/verify_package.py`
(the builder generation, which reads that enum) plus `invariants.py`/`invariants_ext.py`.

Rules honoured: flag, never silently repair (invariant failures and enum drift are declared in
the README, never fixed here); every rate carries numerator, denominator and basis; every
documented number is recomputed from the data at build time and re-derived by the verifier;
checksums are generated by script, never by hand. The findings table is written as-is; the
six HARMONIZATION columns the verifier reads (`tier_source`, `cap_*`, `ontology_id_verification`,
`ontology_id_match_mode`, `ontology_id_prefix`, `hpo_verification`) are APPENDED and listed as
pipeline-derived in DATA_DICTIONARY.md — no existing column is mutated.
"""
